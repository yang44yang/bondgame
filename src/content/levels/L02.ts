const y2 = (y: number) => (y * 100).toFixed(2) + '%';

const lesson = `
你已经知道：一张面值 100、票息 4.5% 的国债，每半年给你 2.25，到期还你 100。这些条款写死在借条上，一辈子不变。你还不知道的是：这张借条从发行到到期的 30 年里，每一天都在市场上转手，转手价几乎从来不是 100。今天（2026-09-29）IBKR 上这只 4.5 Feb'36 的[[价格|Price]]是 ${f2(P0)}。

拿[[定期存单|CD]]打比方。你去年在银行存了一张三年期、年息 4.5% 的存单。今年银行给新客户的三年期利率涨到了 5.1%。这时你想把手里的存单转让给别人，他为什么要接？银行明明给他 5.1%。他只会在一种情况下接：你打折。折到他按这个折扣价买入、拿到期，实际年化也有 5.1% 为止。这个折扣价，就是 ${f2(P0)}。

再换个比方。一套房子签了十年固定租金的[[租约|Lease]]，市场租金涨了，这套房连同租约就没那么值钱了；市场租金跌了，这份锁定高租金的租约反而成了宝贝。租金就是票息，房价就是债券价格。

反过来的例子 IBKR 上也有：2000 年发的一只 6.25% 的老国债（\`6.25 May'30\`），今天卖 ${f2(P30)}，高于面值。因为现在市场利率只有 5% 左右，手里有 6.25% 票息的借条是香饽饽，别人愿意加价买。这叫[[溢价|Premium]]；${f2(P0)} 那种叫[[折价|Discount]]；正好 100 叫[[平价|Par]]。

> 所以价格 Price 和[[到期收益率|Yield to Maturity (YTM)]]是同一件事的两种说法。YTM 是"按今天的价格买入、持有到期、把票息和到期补回面值都算上"的年化回报。利率涨，价格跌；利率跌，价格涨。IBKR 上 ${f2(P0)} 旁边写的两个收益率 5.121% 和 5.103%（一个按买价、一个按卖价，第 5 关细讲），中间就是 ${y2(Y0)}，就是这个数。

折价债的回报来自两块：每年 4.5 的票息，加上到期时 ${f2(P0)} 补回 100 的 ${f2(PULL)} 点。只看第一块，4.5 ÷ ${f2(P0)} = ${CY.toFixed(2)}%，这叫[[当前收益率|Current Yield]]，它不是你的回报；两块合起来摊到 ${f1(years('BOND36'))} 年，才是 ${y2(Y0)}。

一个反直觉的地方：债券价格下跌，对还没买的人是好事（更便宜的入场价、更高的收益率）；对已经持有、马上要卖的人是坏事；对打算持有到期的人无所谓，他拿到的每一笔现金流一分不少。第 3 关和第 8 关会分别展开这两头。

还有一个坑。IBKR 详情页那张走势图默认画的是**收益率 Yield**，不是价格（图上的 O/H/L/C 数值是 5.69、4.50 这种收益率数字，不是价格）。图往上走，是收益率在涨，价格在跌。看图之前先看数值量级。
`;

